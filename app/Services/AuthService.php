<?php

namespace App\Services;

use App\Enums\ApiErrorCode;
use App\Exceptions\ApiException;
use App\Models\User;
use App\Repositories\AuditLogRepository;
use App\Repositories\UserRepository;
use Illuminate\Contracts\Cache\Repository as Cache;
use Illuminate\Contracts\Hashing\Hasher;

/**
 * Authenticates users and issues bearer tokens.
 */
final class AuthService
{
    private const string DUMMY_PASSWORD_HASH_CACHE_KEY = 'auth.dummy_password_hash';

    public function __construct(
        private readonly UserRepository $users,
        private readonly JwtService $jwt,
        private readonly Hasher $hasher,
        private readonly AuditLogRepository $audit,
        private readonly Cache $cache,
    ) {}

    /**
     * Verify credentials and issue a bearer token.
     *
     * @param  string  $traceId  Trace id of the originating request, stored on the audit record.
     * @return array{token: array{access_token: string, token_type: string, expires_in: int}, user: User}
     *
     * @throws ApiException With `INVALID_CREDENTIALS` when the email is unknown or the password does not match.
     */
    public function login(string $email, string $password, string $traceId): array
    {
        $user = $this->users->findByEmail($email);

        if ($user === null) {
            $this->hasher->check($password, $this->dummyPasswordHash());
            $this->recordFailure($traceId, null);

            throw new ApiException(ApiErrorCode::InvalidCredentials);
        }

        if (! $this->hasher->check($password, $user->password)) {
            $this->recordFailure($traceId, $user);

            throw new ApiException(ApiErrorCode::InvalidCredentials);
        }

        $token = $this->issueToken($user);

        // Recorded only after the token exists so a failed issuance cannot leave
        // a success audit behind.
        $this->audit->record(
            $traceId,
            $user,
            AuditLogRepository::ACTION_LOGIN,
            AuditLogRepository::RESULT_SUCCESS,
        );

        return ['token' => $token, 'user' => $user];
    }

    /**
     * Audit a login payload rejected by validation when its email identifies a user.
     *
     * @param  string  $email  Submitted email, which may belong to a registered user.
     * @param  string  $traceId  Trace id of the originating request.
     */
    public function recordValidationFailure(string $email, string $traceId): void
    {
        $user = $this->users->findByEmail($email);

        if ($user === null) {
            return;
        }

        $this->audit->record(
            $traceId,
            $user,
            AuditLogRepository::ACTION_LOGIN,
            AuditLogRepository::RESULT_FAILURE,
            AuditLogRepository::FAILURE_VALIDATION_FAILED,
        );
    }

    /**
     * Hash for the unknown-email path, generated by the configured hasher and
     * cached. Generating it per attempt would add a second hash and reintroduce
     * the timing signal the dummy check exists to remove.
     */
    private function dummyPasswordHash(): string
    {
        $hash = $this->cache->get(self::DUMMY_PASSWORD_HASH_CACHE_KEY);

        if (! is_string($hash) || $this->hasher->needsRehash($hash)) {
            $hash = $this->hasher->make(bin2hex(random_bytes(32)));
            $this->cache->forever(self::DUMMY_PASSWORD_HASH_CACHE_KEY, $hash);
        }

        return $hash;
    }

    /**
     * Record a rejected login attempt, identifying the user when the email exists.
     */
    private function recordFailure(string $traceId, ?User $user): void
    {
        $this->audit->record(
            $traceId,
            $user,
            AuditLogRepository::ACTION_LOGIN,
            AuditLogRepository::RESULT_FAILURE,
            AuditLogRepository::FAILURE_INVALID_CREDENTIALS,
        );
    }

    /**
     * @return array{access_token: string, token_type: string, expires_in: int}
     */
    private function issueToken(User $user): array
    {
        $issued = $this->jwt->issue($user->id);

        return [
            'access_token' => $issued['token'],
            'token_type' => 'Bearer',
            'expires_in' => $issued['expires_in'],
        ];
    }
}
